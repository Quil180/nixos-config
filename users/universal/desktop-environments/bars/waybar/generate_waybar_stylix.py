def apply_wallpaper_style(wallpaper_path):
    print(f"[generate_waybar_stylix] Applying style for wallpaper: {wallpaper_path}", flush=True)
    if not wallpaper_path or not os.path.exists(wallpaper_path):
        print(f"[generate_waybar_stylix] Error: Wallpaper path {wallpaper_path} invalid or missing", file=sys.stderr, flush=True)
        return
